// Assembles every generated design token into one stylesheet.
import { colorScheme, colorCssVars } from './color.js';
import { motionCss } from './motion.js';
import { shapesCss } from './shapes.js';

// M3 type scale. Emphasized styles (new in M3 Expressive) bump the weight.
const TYPE_SCALE = {
  'display-large': [57, 64, -0.25, 400, 500],
  'display-medium': [45, 52, 0, 400, 500],
  'display-small': [36, 44, 0, 400, 500],
  'headline-large': [32, 40, 0, 400, 500],
  'headline-medium': [28, 36, 0, 400, 500],
  'headline-small': [24, 32, 0, 400, 500],
  'title-large': [22, 28, 0, 400, 500],
  'title-medium': [16, 24, 0.15, 500, 700],
  'title-small': [14, 20, 0.1, 500, 700],
  'body-large': [16, 24, 0.5, 400, 500],
  'body-medium': [14, 20, 0.25, 400, 500],
  'body-small': [12, 16, 0.4, 400, 500],
  'label-large': [14, 20, 0.1, 500, 700],
  'label-medium': [12, 16, 0.5, 500, 700],
  'label-small': [11, 16, 0.5, 500, 700],
};

// M3 Expressive corner scale (adds large-increased, extra-large-increased, extra-extra-large).
const CORNERS = {
  none: '0px',
  'extra-small': '4px',
  small: '8px',
  medium: '12px',
  large: '16px',
  'large-increased': '20px',
  'extra-large': '28px',
  'extra-large-increased': '32px',
  'extra-extra-large': '48px',
  full: '9999px',
};

function typographyCss() {
  const lines = [];
  for (const [name, [size, line, tracking, weight, emph]] of Object.entries(TYPE_SCALE)) {
    const font = name.startsWith('display') || name.startsWith('headline') ? 'var(--md-ref-typeface-brand)' : 'var(--md-ref-typeface-plain)';
    lines.push(`  --md-sys-typescale-${name}-font: ${font};`);
    lines.push(`  --md-sys-typescale-${name}-size: ${size / 16}rem;`);
    lines.push(`  --md-sys-typescale-${name}-line-height: ${line / 16}rem;`);
    lines.push(`  --md-sys-typescale-${name}-tracking: ${tracking / 16}rem;`);
    lines.push(`  --md-sys-typescale-${name}-weight: ${weight};`);
    lines.push(`  --md-sys-typescale-emphasized-${name}-weight: ${emph};`);
  }
  return lines.join('\n');
}

function typeClasses() {
  return Object.keys(TYPE_SCALE)
    .map(
      (n) =>
        `.md-typescale-${n} { font-family: var(--md-sys-typescale-${n}-font); font-size: var(--md-sys-typescale-${n}-size); line-height: var(--md-sys-typescale-${n}-line-height); letter-spacing: var(--md-sys-typescale-${n}-tracking); font-weight: var(--md-sys-typescale-${n}-weight); }\n` +
        `.md-typescale-${n}.emphasized, .md-typescale-emphasized-${n} { font-weight: var(--md-sys-typescale-emphasized-${n}-weight); }`
    )
    .join('\n');
}

export function tokensCss(theme) {
  const { seedColor, variant, contrast = 0, motion = 'expressive', fontBrand, fontPlain } = theme;
  const light = colorScheme(seedColor, { dark: false, variant, contrast });
  const dark = colorScheme(seedColor, { dark: true, variant, contrast });
  const shapes = shapesCss();
  const corners = Object.entries(CORNERS).map(([k, v]) => `  --md-sys-shape-corner-${k}: ${v};`).join('\n');
  const fontStack = (f) => `${f.includes(' ') ? `'${f}'` : f}, system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif`;

  return `/* Generated by m3blog — do not edit. Seed ${seedColor}, variant ${variant}, motion ${motion}. */
:root {
  color-scheme: light;
${colorCssVars(light)}
  --md-ref-typeface-brand: ${fontStack(fontBrand)};
  --md-ref-typeface-plain: ${fontStack(fontPlain)};
  --md-ref-typeface-mono: 'Roboto Mono', ui-monospace, 'SFMono-Regular', Menlo, Consolas, monospace;
${typographyCss()}
${corners}
${motionCss(motion)}
  --md-sys-state-hover-opacity: 0.08;
  --md-sys-state-focus-opacity: 0.1;
  --md-sys-state-pressed-opacity: 0.1;
  --md-sys-state-dragged-opacity: 0.16;
  --md-sys-elevation-level0: none;
  --md-sys-elevation-level1: 0 1px 2px 0 rgb(0 0 0 / 0.3), 0 1px 3px 1px rgb(0 0 0 / 0.15);
  --md-sys-elevation-level2: 0 1px 2px 0 rgb(0 0 0 / 0.3), 0 2px 6px 2px rgb(0 0 0 / 0.15);
  --md-sys-elevation-level3: 0 1px 3px 0 rgb(0 0 0 / 0.3), 0 4px 8px 3px rgb(0 0 0 / 0.15);
  --md-sys-elevation-level4: 0 2px 3px 0 rgb(0 0 0 / 0.3), 0 6px 10px 4px rgb(0 0 0 / 0.15);
  --md-sys-elevation-level5: 0 4px 4px 0 rgb(0 0 0 / 0.3), 0 8px 12px 6px rgb(0 0 0 / 0.15);
${shapes.vars}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorCssVars(dark, '    ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${colorCssVars(dark)}
}
@media (prefers-reduced-motion: reduce) {
  :root {
${motionCss(motion).split('\n').filter((l) => l.includes('-duration:')).map((l) => `  ${l.replace(/\d+ms;$/, '1ms;')}`).join('\n')}
  }
}
${typeClasses()}
${shapes.classes}
${shapes.keyframes}
`;
}
